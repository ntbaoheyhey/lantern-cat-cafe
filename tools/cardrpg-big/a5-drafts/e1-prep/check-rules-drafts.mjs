import {createRequire} from 'node:module';
import {readFile,mkdir,writeFile} from 'node:fs/promises';
import {resolve,dirname} from 'node:path';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=process.cwd(),prep='/tmp/cardrpg-a5-e1-prep',out=prep+'/checks';
await mkdir(out,{recursive:true});
const files=['outcome-v4','recommendation-v4','forecast-v4','forecast-key-v4'];
const overlay=Object.fromEntries(files.map(f=>[resolve(root,'packages/game-rules/src/cardrpg/depth',f+'.ts'),resolve(prep,f+'.ts')]));
const require=createRequire(root+'/apps/web/package.json');
const {build}=await import(require.resolve('vite'));
const entry=out+'/entry.ts';
await writeFile(entry,`export * as R from '${root}/packages/game-rules/src/cardrpg/depth/index.ts';\n`+files.map((f,i)=>`export * as M${i} from '${root}/packages/game-rules/src/cardrpg/depth/${f}.ts';`).join('\n'));
await build({root,configFile:false,publicDir:false,envDir:false,logLevel:'silent',plugins:[{name:'isolated-e1-drafts',enforce:'pre',resolveId(source,importer){
 const base=source.startsWith('/')?source:source.startsWith('.')&&importer?resolve(dirname(importer),source):null;
 if(base)for(const p of [base,base+'.ts'])if(overlay[p])return p;
},async load(id){if(overlay[id])return readFile(overlay[id],'utf8');}}],build:{outDir:out,emptyOutDir:false,minify:false,lib:{entry,formats:['es'],fileName:()=> 'drafts.mjs'}}});
const {R,M0:O,M1:A,M3:K}=await import(pathToFileURL(out+'/drafts.mjs'));
const s=R.setGameplayV4(R.createDepthAccount(7),true),copy=structuredClone(s),checks=[];
const wrong=A.changeBuildV4(s,{kind:'row',catId:'unknown',row:'front'});assert(!wrong.ok);assert.equal(wrong.state,s);
const noFront=A.changeBuildV4(s,{kind:'row',catId:'mochi',row:'rear'});assert(!noFront.ok);assert.equal(noFront.state,s);
assert(A.changeBuildV4(s,{kind:'plan',plan:{focus:'leader',care:'protect'}}).ok);assert.deepEqual(s,copy);
const active=R.startRun(s,1,17).state;
for(const c of [{kind:'row',catId:'soot',row:'front'},{kind:'plan',plan:{focus:'leader',care:'protect'}},{kind:'level',cardId:s.account.cards[0].id}])assert(!A.changeBuildV4(active,c).ok);
checks.push('Public changes reject missing cats, empty front, active run; input unchanged');
const setup={seed:1,chapter:1,gameplayV4:true,cats:R.battleCats(s),enemies:['practice-cushion']};
assert.equal(K.forecastKeyV4(setup),K.forecastKeyV4({...setup,seed:500}));
assert.notEqual(K.forecastKeyV4(setup),K.forecastKeyV4({...setup,plan:{focus:'leader',care:'protect'}}));
checks.push('Forecast key excludes encounter RNG and includes plan');
const path=root+'/reports/cardrpg-big/a5/h0/day7/checks.json';
const receipt=JSON.parse(await readFile(path,'utf8'));
const b=receipt.encounters.find(e=>e.kind==='boss').battle,before=JSON.stringify(b),result=O.outcomeV4(b);
assert.equal(JSON.stringify(b),before);assert.deepEqual(result.reconstructedRows,Object.fromEntries(b.actors.filter(a=>a.side==='party').map(a=>[a.id,a.row])));
assert.equal(result.firstFallen.id,'mochi');assert.equal(result.causes.length,3);assert(result.causes.every(c=>c.amount>0&&c.text.includes(b.actors.find(a=>a.id===c.actorId).name)));
checks.push('Earned day7 receipt: exact row reconstruction, named top3 and first fallen, no mutation');
const started=performance.now(),advice=A.recommendBuildV4(s,setup),elapsedMs=performance.now()-started;
assert.deepEqual(s,copy);
if(advice){assert.equal(advice.samples,10);assert(advice.after.wins>=advice.before.wins);assert(A.applyAdviceV4(s,advice).ok);
 const stale=structuredClone(s);stale.account.currencies.fish+=1;assert(!A.applyAdviceV4(stale,advice).ok);assert.equal(A.applyAdviceV4(stale,advice).state,stale);}
checks.push('Recommendation uses fixed paired TRAIN samples and atomic available commands; no input mutation');
const hashes=Object.fromEntries(await Promise.all(Object.entries(overlay).map(async([logical,file])=>[logical,createHash('sha256').update(await readFile(file)).digest('hex')])));
await writeFile(out+'/results.json',JSON.stringify({status:'Isolated checks only; no adoption/typecheck/browser timing claim',checks,elapsedMs,advice,hashes,day7Outcome:result},null,2));
console.log(JSON.stringify({checks,elapsedMs,hasAdvice:!!advice}));
