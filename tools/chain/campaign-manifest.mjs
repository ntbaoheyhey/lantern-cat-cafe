import {createHash} from 'node:crypto';
import {readFileSync,readdirSync,writeFileSync} from 'node:fs';
import {resolve,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const collect=dir=>readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?collect(resolve(dir,e.name)):[resolve(dir,e.name)]);
const files=[...collect(resolve(root,'packages/game-rules/src')).filter(f=>f.endsWith('.ts')&&!f.endsWith('.test.ts')),
 'packages/chain/src/campaign.ts','supabase/functions/_shared/chain-campaign.ts','supabase/functions/_shared/chain-campaign-service.ts'].map(p=>resolve(root,p)).sort();
const h=createHash('sha256');for(const f of files)h.update(relative(root,f)).update('\0').update(readFileSync(f)).update('\0');
const hash=h.digest('hex');
const output=`// Generated by tools/chain/campaign-manifest.mjs. No authority is enabled by this file.\nexport const CAMPAIGN_RULES_HASH='${hash}';\n`;
const dest=resolve(root,'supabase/functions/_shared/chain-campaign-manifest.ts');
if(process.argv.includes('--check')){if(readFileSync(dest,'utf8')!==output)throw new Error('Campaign rules changed; regenerate manifest and explicitly migrate campaign policies.');}
else writeFileSync(dest,output);
console.log(JSON.stringify({campaignRulesHash:hash,sourceFiles:files.length,checked:process.argv.includes('--check')}));
