// Regenerates src/abi.ts from Foundry build output. Run `forge build` in contracts/ first.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, '../../contracts/out');
const contracts = { relicForgeAbi: 'RelicForge', relicNftAbi: 'RelicNFT', relicMarketAbi: 'RelicMarket', yarnTokenAbi: 'YarnToken', relicMarketV2Abi: 'RelicMarketV2', seasonRewardsAbi: 'SeasonRewards' };

let src = '// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit by hand.\n';
for (const [name, contract] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(`${out}/${contract}.sol/${contract}.json`, 'utf8'));
  src += `\nexport const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
}
writeFileSync(resolve(root, 'src/abi.ts'), src);
console.log('wrote src/abi.ts');
