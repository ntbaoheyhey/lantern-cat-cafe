import {test,expect} from '@playwright/test';
import {readFileSync} from 'node:fs';
import {createPublicClient,createWalletClient,http,parseEther,type Abi,type Address} from 'viem';
import {mnemonicToAccount} from 'viem/accounts';
import {avalancheFuji} from 'viem/chains';
import {relicNftAbi,relicMarketV2Abi,yarnTokenAbi,relicForgeAbi} from '../../../../packages/chain/src/abi';
const client=createPublicClient({chain:avalancheFuji,transport:http('http://127.0.0.1:5981')});
const fixture=(i:number)=>mnemonicToAccount('test test test test test test test test test test test junk',{addressIndex:i});
test('buy two Epic units → irreversible forge → permanent ornament; retry never charges',async({page})=>{
  const c=JSON.parse(readFileSync('public/chain-local.json','utf8')) as Record<string,Address>;
  const seller=fixture(7),signer=fixture(2),wallet=createWalletClient({chain:avalancheFuji,account:seller,transport:http('http://127.0.0.1:5981')});
  const send=async(address:Address,abi:Abi,functionName:string,args:readonly unknown[])=>{
    const request=await client.simulateContract({address,abi,functionName,args,account:seller});
    const hash=await wallet.writeContract({...request.request,account:seller});
    expect((await client.waitForTransactionReceipt({hash})).status).toBe('success');
  };
  for(let n=0;n<2;n++){
    const voucher={player:seller.address,relicId:20020n,rarity:2,nonce:90001n+BigInt(n),expiry:BigInt(Math.floor(Date.now()/1000)+3600)};
    const signature=await signer.signTypedData({domain:{name:'TaskbarHeroRelic',version:'1',chainId:43113,verifyingContract:c.RelicNFT},primaryType:'Voucher',types:{Voucher:[{name:'player',type:'address'},{name:'relicId',type:'uint256'},{name:'rarity',type:'uint8'},{name:'nonce',type:'uint256'},{name:'expiry',type:'uint256'}]},message:voucher});
    await send(c.RelicNFT!,relicNftAbi,'mint',[voucher,signature]);
  }
  await send(c.RelicNFT!,relicNftAbi,'setApprovalForAll',[c.RelicMarketV2,true]);
  const listing=await client.readContract({address:c.RelicMarketV2!,abi:relicMarketV2Abi,functionName:'nextListingId'});
  await send(c.RelicMarketV2!,relicMarketV2Abi,'list',[20020n,2n,parseEther('2'),1]);
  await page.goto('/?demo=1&squad=1&cardrpg2=1&a6=1');
  await page.getByRole('button',{name:'▶ Play as guest'}).click();
  await expect(page.getByTestId('chain-gas')).toHaveText('▲ 0.0500');
  const who=(await page.getByTestId('chain-address').getAttribute('title')) as Address;
  await page.getByRole('button',{name:'◈ Market',exact:true}).click();
  const room=page.getByRole('dialog',{name:'Fuji market',exact:true});
  const tab=async(name:string)=>room.getByRole('navigation',{name:'Chain screens'}).getByRole('button',{name,exact:true}).click();
  const closeReceipt=async()=>{const sheet=room.getByRole('dialog',{name:'Transaction confirmed'});await expect(sheet).toBeVisible();await sheet.getByRole('button',{name:'Close receipt'}).click();};
  await room.getByRole('button',{name:'🎟 Judge pass'}).click();
  await room.getByRole('button',{name:'🧶 Claim',exact:true}).click();await closeReceipt();
  await tab('Forge');
  const trial=process.env.CHAIN_SEAL_PRICE_TRIAL==='1';
  await expect(room.getByTestId('forge-budget')).toHaveText(trial?'Self-seal 🧶 10 + 3 = 13':'Self-seal 🧶 20 + 3 = 23');
  if(trial)await expect(room.getByTestId('forge-shortfall')).toHaveCount(0);
  else await expect(room.getByTestId('forge-shortfall')).toHaveText('Short 🧶 3');
  await expect(room.getByRole('button',{name:'✦ Forge',exact:true})).toBeDisabled();
  await page.setViewportSize({width:390,height:844});
  expect(await room.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
  await page.screenshot({path:trial?'../../reports/chain/shots/H5-forge-budget-trial-mobile.png':'../../reports/chain/shots/H5-forge-budget-mobile.png'});
  await page.setViewportSize({width:1280,height:900});
  await tab('Market');await room.getByLabel('Currency',{exact:true}).selectOption('1');
  const lot=room.getByTestId(`listing-${listing}`);
  while(!await lot.count())await room.getByRole('button',{name:'Next listings'}).click();
  await lot.getByRole('button',{name:'↓ Buy'}).click();await closeReceipt();
  await tab('Forge');
  await expect(room.getByTestId('forge-budget')).toHaveText('Self-seal 🧶 0 + 3 = 3');
  await expect(room.getByTestId('forge-shortfall')).toHaveCount(0);
  await expect(room.getByRole('button',{name:'✦ Forge',exact:true})).toBeDisabled();
  await room.getByLabel('Epic 1',{exact:true}).selectOption('20020');
  await room.getByLabel('Epic 2',{exact:true}).selectOption('20020');
  const supply=await client.readContract({address:c.YarnToken!,abi:yarnTokenAbi,functionName:'totalSupply'});
  await room.getByRole('button',{name:'✦ Forge',exact:true}).click();
  await expect(room.getByText('Consume both forever.')).toBeVisible();
  await room.getByRole('button',{name:'🔥 Confirm',exact:true}).click();await closeReceipt();
  await expect(room.getByTestId('forge-unlocked')).toHaveText('✓ Unlocked');
  const balance=(owner:Address)=>client.readContract({address:c.RelicNFT!,abi:relicNftAbi,functionName:'balanceOf',args:[owner,20020n]});
  expect(await balance(who)).toBe(0n);expect(await balance(c.RelicForge!)).toBe(2n);
  expect(await client.readContract({address:c.YarnToken!,abi:yarnTokenAbi,functionName:'totalSupply'})).toBe(supply-parseEther('3'));
  expect(await client.readContract({address:c.RelicForge!,abi:relicForgeAbi,functionName:'hasDesign',args:[who,0]})).toBe(true);
  await page.setViewportSize({width:390,height:844});
  await expect(room).toBeVisible();
  expect(await room.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
  await page.screenshot({path:'../../reports/chain/shots/H5-forge-mobile.png'});
  // Real reload models a lost successful receipt. Ownership comes from chain.
  await page.reload();await page.getByRole('button',{name:'◈ Market',exact:true}).click();await tab('Forge');
  await expect(room.getByTestId('forge-unlocked')).toHaveText('✓ Unlocked');
  await room.getByRole('button',{name:'Refresh chain'}).click();
  expect(await client.readContract({address:c.YarnToken!,abi:yarnTokenAbi,functionName:'totalSupply'})).toBe(supply-parseEther('3'));
});
