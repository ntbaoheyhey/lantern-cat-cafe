import {spawn} from 'node:child_process';
import {readFile,writeFile,copyFile,mkdir} from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {withTimingLock} from '../../../tools/cardrpg-look/lock.mjs';
await withTimingLock('LOOK L4 byte-preserving offline packing validation',async()=>{
 const out='reports/cardrpg-look/rounds/effects/round-4-material/lossless-packing';await mkdir(out);
 await new Promise((resolve,reject)=>{const child=spawn(process.execPath,['tools/cardrpg-look/build.mjs'],{stdio:'inherit'});child.once('error',reject);child.once('close',code=>code?reject(Error(`Build ${code}`)):resolve())});
 const before=await readFile('/tmp/cardrpg-look-l4-material4.html','utf8'),after=await readFile('docs/cardrpg-look/index.html','utf8');
 const pattern=/<script id="([^"]+)" type="application\/octet-stream">([^<]+)<\/script>/g;
 const payloads=html=>new Map([...html.matchAll(pattern)].map(m=>[m[1],gunzipSync(Buffer.from(m[2],'base64'))]));
 const old=payloads(before),current=payloads(after);assert.deepEqual([...current.keys()],[...old.keys()]);
 for(const [id,bytes] of current)assert.deepEqual(bytes,old.get(id),id);
 const shell=html=>html.replace(pattern,(_all,id)=>`<payload id="${id}"/>`);assert.equal(shell(after),shell(before));
 assert(Buffer.byteLength(after)<=24000000);
 const hash=s=>createHash('sha256').update(s).digest('hex');
 const receipt={at:new Date().toISOString(),beforeSha256:hash(before),afterSha256:hash(after),beforeBytes:Buffer.byteLength(before),afterBytes:Buffer.byteLength(after),saved:Buffer.byteLength(before)-Buffer.byteLength(after),payloadsExact:current.size,shellExact:true,notPhaseAcceptance:true};
 await copyFile('docs/cardrpg-look/index.html','/tmp/cardrpg-look-l4-lossless.html');await copyFile('docs/cardrpg-look/build.json',`${out}/build.json`);await writeFile(`${out}/checks.json`,JSON.stringify(receipt,null,2)+'\n');console.log(JSON.stringify(receipt));
});
