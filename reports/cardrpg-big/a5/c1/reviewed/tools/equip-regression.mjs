import { chromium } from '/Users/bao/taskbar-hero-cardrpg-a4/apps/web/node_modules/@playwright/test/index.mjs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const artifact='/tmp/cardrpg-a5-c1-revision/artifact/index.html';
const out='/tmp/cardrpg-a5-c1-revision/equip-regression';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chromium',headless:true,args:['--use-angle=metal']});
const page=await browser.newPage({viewport:{width:1280,height:720}}),errors=[],checks=[];
page.on('pageerror',e=>errors.push(String(e)));
const button=name=>page.getByRole('button',{name,exact:true});
const group=(name,value)=>page.getByRole('group',{name,exact:true}).getByRole('button',{name:value,exact:true});
const read=()=>page.evaluate(()=>window.__depthReview.state);
try{
 await page.goto('file://'+artifact);
 await page.getByRole('heading',{name:'A small light. A brave little team.'}).waitFor({timeout:120000});
 await page.getByRole('navigation',{name:'Cafe screens'}).getByRole('button',{name:'Equipment',exact:true}).click();
 const before=await read();
 assert.equal(await page.locator('.dp-equip-action h2').innerText(),'Common Hearthloom Pan');
 await group('Slot','outfit').click();await group('Equip for','Soot').click();
 const selected='Common Hearthloom Apron';
 assert.equal(await page.locator('.dp-equip-action h2').innerText(),selected);
 assert.equal(await page.locator('.dp-gear-detail h2').innerText(),selected);
 assert.equal(await page.locator('.dp-gear-grid button[aria-pressed="true"] b').innerText(),selected);
 await button('Equip selected').click();
 const equipped=await read();
 assert.equal(equipped.equipment.soot.outfit,before.equipment.mochi.outfit);
 assert.equal(equipped.equipment.mochi.outfit,undefined);
 assert.equal(equipped.equipment.soot.weapon,before.equipment.soot.weapon);
 assert.equal(equipped.equipment.mochi.weapon,before.equipment.mochi.weapon);
 checks.push('outfit filter aligns grid selection, comparison and Equip; actual command moves the visible outfit only');
 await page.locator('.dp-v4-filters').scrollIntoViewIfNeeded();await page.screenshot({path:out+'/equipped-outfit.png'});
 await group('Rarity','legendary').click();
 assert.equal(await page.locator('.dp-gear-grid button').count(),0);
 for(const selector of ['.dp-equip-action','.dp-gear-detail','.dp-compare'])assert.equal(await page.locator(selector).count(),0);
 assert.equal(await button('Equip selected').count(),0);
 await page.getByText('No equipment matches these filters.',{exact:true}).waitFor();
 assert.deepEqual(await read(),equipped);
 checks.push('empty filter removes item actions and comparison without mutating the saved account');
 await page.locator('.dp-v4-filters').scrollIntoViewIfNeeded();await page.screenshot({path:out+'/empty-filter.png'});
 await group('Rarity','All rarities').click();
 await page.locator('.dp-v4-filters summary').click();
 await group('Ownership','Available').click();
 assert.equal(await page.locator('.dp-equip-action h2').innerText(),'Common Moonwick Shawl');
 await button('Equip selected').click();
 assert.equal((await read()).equipment.soot.outfit,before.equipment.soot.outfit);
 checks.push('available ownership filter equips the displaced outfit from the shelf');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth),0);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,checks}));
}finally{
 await writeFile(out+'/checks.json',JSON.stringify({artifact,sha256:createHash('sha256').update(await readFile(artifact)).digest('hex'),checks,errors},null,2));
 await browser.close();
}
