function formatPassive(p: ClassDef['passive']): string {
  switch (p.id) {
    case 'cleave':
      return `Cleave (\`cleave\`): every ${p.params.every} attacks, deal ${p.params.splash * 100}% splash damage to the next monster`;
    case 'bonk':
      return `Bonk (\`bonk\`): each hit delays target attack by ${p.params.delayMs} ms`;
    case 'twinStrike':
      return `Twin Strike (\`twinStrike\`): ${p.params.hits} hits per attack`;
    case 'markPrey':
      return `Mark Prey (\`markPrey\`): marks target (+${p.params.damageTaken * 100}% damage taken), +${p.params.materialFind * 100}% material find`;
    case 'volley':
      return `Volley (\`volley\`): every ${p.params.every} shots fires ${p.params.arrows} arrows (extra arrows deal ${p.params.extraArrowDamage * 100}% damage)`;
    case 'burn':
      return `Burn (\`burn\`): splash ${p.params.splash * 100}%, burn ${p.params.burnFraction * 100}% damage over ${p.params.durationMs} ms (ticks every ${p.params.tickMs} ms)`;
    case 'poison':
      return `Poison (\`poison\`): poison ${p.params.poisonFraction * 100}% damage over ${p.params.durationMs} ms (ticks every ${p.params.tickMs} ms), heal ${p.params.healOnKill * 100}% max HP on kill`;
  }
}

function formatStats(stats: Record<string, number | undefined>): string {
  return Object.entries(stats)
    .filter(([, v]) => v !== undefined && v > 0)
    .map(([k, v]) => `${k}: ${v}`)
    .join(', ');
}

export function generateContentDocs(): string {
  const lines: string[] = [];
  const push = (...l: string[]) => lines.push(...l);

  // Top notice
  push(
    '<!--',
    '  AUTOGENERATED FILE — DO NOT EDIT DIRECTLY.',
    '  Generated from the v2 content registry in packages/game-rules/src/v2/content/.',
    '  To regenerate, run: node scripts/gen-content-docs.mjs',
    '  (or UPDATE_DOCS=1 pnpm --filter @taskbar-hero/game-rules test src/v2/content/docs.gen.test.ts)',
    '-->',
    '',
    '# Cat RPG v2 Content Registry Reference',
    '',
    'Human-readable specification of the Cat RPG v2 content registry, generated directly from code so documentation cannot drift from runtime truth.',
    '',
    '## Table of Contents',
    '',
    '- [Classes and Weapon Profiles](#classes-and-weapon-profiles)',
    '- [Gear Rarities and Bonus Lines](#gear-rarities-and-bonus-lines)',
    '- [Equipment Slots](#equipment-slots)',
    '- [Materials](#materials)',
    '- [Monsters and Bosses per Chapter](#monsters-and-bosses-per-chapter)',
    '- [Recipes, Salvage, and Relic Forge](#recipes-salvage-and-relic-forge)',
    '- [Chests and Loot Tables](#chests-and-loot-tables)',
    '- [Equipment Catalog](#equipment-catalog)',
    '',
    '---',
    '',
    '## Classes and Weapon Profiles',
    '',
    'The 7 playable cat hero classes and their core combat profiles. ATK multipliers scale damage per hit; slow and multi-hit classes are balanced around close DPS against the reference Warrior once passives are factored.',
    '',
    '### Classes',
    '',
    '| Class | ID | Weapon Type | Range / Role | Stat Leanings (HP / ATK / DEF) | Attack Interval | Base Crit | Base Dodge | Passive | Starter Weapon |',
    '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
  );

  for (const c of CLASSES) {
    const statsStr = `HP x${c.stats.hp}, ATK x${c.stats.atk}, DEF x${c.stats.def}`;
    const critStr = `${c.critChance * 100}% (${c.critMultiplier}x)`;
    const dodgeStr = `${c.dodge * 100}%`;
    const intervalStr = `${c.attackIntervalMs} ms (${(c.attackIntervalMs / 1000).toFixed(2)}s)`;
    const passiveStr = formatPassive(c.passive);
    push(
      `| ${c.name} | \`${c.id}\` | \`${c.weaponType}\` | ${c.range} | ${statsStr} | ${intervalStr} | ${critStr} | ${dodgeStr} | ${passiveStr} | \`${c.starterWeaponId}\` |`,
    );
  }

  push(
    '',
    '### Weapon Profiles',
    '',
    'Attack cadence, swing windup, and hit timing for all 7 weapon families.',
    '',
    '| Weapon Type | Windup | Hit Moments | Projectile | Range Type |',
    '| --- | --- | --- | --- | --- |',
  );

  for (const w of WEAPON_TYPES) {
    const hitMoments = w.hitAtMs.map((ms) => `${ms} ms`).join(', ');
    const projStr = w.projectile ? `${w.projectile.kind} (travel: ${w.projectile.travelMs} ms)` : 'None (instant melee)';
    const cls = CLASSES.find((c) => c.weaponType === w.id);
    const rangeType = cls ? cls.range : '-';
    push(`| \`${w.id}\` | ${w.windupMs} ms | ${hitMoments} | ${projStr} | ${rangeType} |`);
  }

  push(
    '',
    '---',
    '',
    '## Gear Rarities and Bonus Lines',
    '',
    'v2 gear items span 5 rarity tiers. Items gain higher base stat multipliers, more rolled bonus lines, and higher max item levels as rarity increases.',
    '',
    '### Rarities',
    '',
    '| Rarity | ID | Stat Multiplier | Bonus Lines | Max Item Level |',
    '| --- | --- | --- | --- | --- |',
  );

  for (const r of GEAR_RARITIES) {
    const name = r.id.charAt(0).toUpperCase() + r.id.slice(1);
    push(`| ${name} | \`${r.id}\` | ${r.statMultiplier}x | ${r.bonusLines} | Lv ${r.maxLevel} |`);
  }

  push(
    '',
    '### Stats and Bonus Line Ranges',
    '',
    'Flat stats (`hp`, `atk`, `def`) are base stats. Fractional stats (e.g. `critChance`, `dodge`) roll as bonus lines with ranges that scale with rarity.',
    '',
    '| Stat ID | Kind | Bonus Line? | Common | Uncommon | Rare | Epic | Legendary |',
    '| --- | --- | --- | --- | --- | --- | --- | --- |',
  );

  for (const s of STATS) {
    const ranges = BONUS_LINE_RANGES[s.id];
    if (!ranges) {
      push(`| \`${s.id}\` | ${s.kind} | No | - | - | - | - | - |`);
    } else {
      const fmtRange = (r: readonly [number, number] | undefined) => (r ? `${(r[0] * 100).toFixed(1)}% - ${(r[1] * 100).toFixed(1)}%` : '-');
      push(
        `| \`${s.id}\` | ${s.kind} | Yes | ${fmtRange(ranges.common)} | ${fmtRange(ranges.uncommon)} | ${fmtRange(ranges.rare)} | ${fmtRange(ranges.epic)} | ${fmtRange(ranges.legendary)} |`,
      );
    }
  }

  push(
    '',
    '---',
    '',
    '## Equipment Slots',
    '',
    'Cats equip 9 gear items across 5 main slots (drawn on character) and 4 accessory slots (secondary stats only). Main slots are unlocked at level 1; accessory slots unlock as the cat levels up.',
    '',
    '| Slot ID | Group | Drawn on Cat | Unlock Level | Primary / Shared Base Stats |',
    '| --- | --- | --- | --- | --- |',
  );

  for (const slot of GEAR_SLOTS) {
    const visibleStr = slot.visible ? 'Yes' : 'No';
    const primaryStr = slot.primaryStats.length > 0 ? slot.primaryStats.map((st) => `\`${st}\``).join(', ') : 'None (design-specific)';
    push(`| \`${slot.id}\` | ${slot.group} | ${visibleStr} | Cat Level ${slot.unlockLevel} | ${primaryStr} |`);
  }

  push(
    '',
    '---',
    '',
    '## Materials',
    '',
    'Currencies and crafting components used for forging gear and Relics.',
    '',
    '| Material ID | Name | Tier | Max Stack | Sources | v1 Legacy Field |',
    '| --- | --- | --- | --- | --- | --- |',
  );

  const materialSources: Record<string, string> = {
    yarn: 'Monster drops (all chapters), chapter chests (first clear & repeat), gear salvage',
    fluffTuft: 'Chapter chests 1-5 (first clear & repeat), salvage Common and Uncommon gear',
    shinyButton: 'Chapter chests 1-5 (first clear & repeat), salvage Rare gear',
    catnipCrystal: 'Chapter chests 2-5 (first clear & repeat), salvage Epic gear',
    starlightScale: 'Chapter chests 3-5 (first clear & repeat), salvage Legendary gear',
    moonPearl: 'Chapter chests 1-5 (100% first clear, 30% repeat chance)',
    catKey: 'Daily login reward (1 per day)',
  };

  for (const m of MATERIALS) {
    const tierStr = typeof m.tier === 'number' ? `Tier ${m.tier}${m.tier === 0 ? ' (Base)' : ''}` : m.tier === 'relic' ? 'Relic' : 'Key';
    const src = materialSources[m.id] ?? '-';
    const v1 = m.v1Field ? `\`${m.v1Field}\`` : '-';
    push(`| \`${m.id}\` | ${m.name} | ${tierStr} | ${m.maxStack.toLocaleString()} | ${src} | ${v1} |`);
  }

  push(
    '',
    '---',
    '',
    '## Monsters and Bosses per Chapter',
    '',
    'Monsters scale their baseline HP, ATK, and XP from the stage formula. Individual monsters modify these baseline stats with archetype multipliers.',
    '',
    '### Archetype Multipliers',
    '',
    '| Archetype | HP Multiplier | ATK Multiplier | XP Multiplier | Loot Multiplier | Role / Behavior |',
    '| --- | --- | --- | --- | --- | --- |',
    '| Balanced Regular | 1.0x | 1.0x | 1.0x | 1.0x | Standard regular monster |',
    '| Swift Regular | 0.8x | 1.2x | 1.0x | 1.0x | Fast glass-cannon regular |',
    '| Sturdy Regular | 1.2x | 0.8x | 1.0x | 1.0x | Tanky defensive regular |',
    '| Elite | 3.0x | 1.5x | 3.0x | 3.0x | Miniboss concluding each round |',
    '| Boss | 40.0x | 2.5x | 25.0x | 0.0x | Climax encounter of the chapter |',
    '',
    '### Chapters and Roster',
  );

  for (const ch of CHAPTERS) {
    push(
      '',
      `#### Chapter ${ch.index}: ${ch.name} (\`${ch.id}\`)`,
      '',
      `- **Background Asset**: \`${ch.background}\``,
      `- **Structure**: ${ch.roundsPerChapter} rounds per chapter, ${ch.killsPerRound} kills per round (last kill of each round is the Elite).`,
      `- **First-Clear Chest Table**: \`${ch.chests.firstClear}\``,
      `- **Repeat Chest Table**: \`${ch.chests.repeat}\``,
      '',
      '| Monster ID | Name | Kind | HP Mul | ATK Mul | XP Mul | Loot Mul |',
      '| --- | --- | --- | --- | --- | --- | --- |',
    );

    const chapterMonsters = MONSTERS.filter((m) => m.chapter === ch.index);
    for (const m of chapterMonsters) {
      push(`| \`${m.id}\` | ${m.name} | ${m.kind} | ${m.hpMul}x | ${m.atkMul}x | ${m.xpMul}x | ${m.lootMul}x |`);
    }
  }

  push(
    '',
    '---',
    '',
    '## Recipes, Salvage, and Relic Forge',
    '',
    'Equipment crafting requires Yarn, tier-appropriate materials, and Fish. Salvaging returns approximately 25% of the crafting cost, guaranteeing craft-then-salvage always incurs a net loss.',
    '',
    '### Gear Forge Recipes',
    '',
    '| Recipe ID | Target Rarity | Fish Cost | Required Materials |',
    '| --- | --- | --- | --- |',
  );

  for (const r of RECIPES) {
    const matsStr = Object.entries(r.materials)
      .map(([m, qty]) => `${qty} \`${m}\``)
      .join(', ');
    push(`| \`${r.id}\` | \`${r.rarity}\` | ${r.fish} | ${matsStr} |`);
  }

  push(
    '',
    '### Gear Salvage Returns',
    '',
    '| Gear Rarity | Materials Recovered | Net Economy Purpose |',
    '| --- | --- | --- |',
  );

  for (const s of SALVAGE) {
    const matsStr = Object.entries(s.materials)
      .map(([m, qty]) => `${qty} \`${m}\``)
      .join(', ');
    push(`| \`${s.rarity}\` | ${matsStr} | Returns ~25% of craft cost; prevents infinite recycling loops |`);
  }

  push(
    '',
    '### Daily Relic Recipe',
    '',
    '| Recipe ID | Description | Required Materials | Daily Limit |',
    '| --- | --- | --- | --- |',
    `| \`${RELIC_RECIPE.id}\` | Daily Relic NFT Forge | ${RELIC_RECIPE.materials.yarn} \`yarn\`, ${RELIC_RECIPE.materials.moonPearl} \`moonPearl\` | ${RELIC_RECIPE.perDay} craft per day |`,
    '',
    '---',
    '',
    '## Chests and Loot Tables',
    '',
  );

  const hasDropRatesDoc = existsSync(DROP_RATES_DOC_PATH);
  if (hasDropRatesDoc) {
    push(
      'Detailed drop probabilities and roll simulations are documented in [drop-rates-v2.md](drop-rates-v2.md).',
      '',
    );
  } else {
    push(
      '> Note: `docs/drop-rates-v2.md` does not currently exist on `main`. Below is the complete listing of chest and nested gear table IDs registered in code.',
      '',
    );
  }

  push(
    '### Scaling and Smart Loot Rules',
    '',
    `- **Amount Growth Factor**: \`${CHEST_SCALING.amountGrowth}\`x scaling per chapter index after the first (\`2^(chapter - 1)\`).`,
    `- **Fish Unit Size**: \`${FISH_UNIT}\` Fish per counted unit.`,
    `- **Smart Loot Class Weapon Share**: \`${SMART_LOOT.classWeaponShare * 100}%\` of weapon drops are biased to the player's active class weapon.`,
    '',
    '### Chest Loot Table IDs',
    '',
    '| Table ID | Chapter | Type | Contents / Subtables |',
    '| --- | --- | --- | --- |',
  );

  for (let ch = 1; ch <= 5; ch++) {
    const p = `ch${ch}`;
    push(
      `| \`chest.${p}.first\` | Chapter ${ch} | First-Clear Chest | Fish, Yarn, Fluff Tuft, Shiny Button, Moon Pearl, Catnip Crystal (Ch2+), Starlight Scale (Ch3+), nested gear tables |`,
      `| \`chest.${p}.repeat\` | Chapter ${ch} | Repeat Chest | Fish, Yarn, Fluff Tuft, Shiny Button, Catnip Crystal (Ch2+), Starlight Scale (Ch3+), 30% Moon Pearl, nested gear tables |`,
      `| \`gear.${p}.first.main\` | Chapter ${ch} | First-Clear Main Gear | Main slot items with first-clear rarity weights |`,
      `| \`gear.${p}.first.accessory\` | Chapter ${ch} | First-Clear Accessory Gear | Accessory items with first-clear rarity weights |`,
      `| \`gear.${p}.repeat.main\` | Chapter ${ch} | Repeat Main Gear | Main slot items with repeat rarity weights |`,
      `| \`gear.${p}.repeat.accessory\` | Chapter ${ch} | Repeat Accessory Gear | Accessory items with repeat rarity weights |`,
    );
  }

  push(
    '',
    '---',
    '',
    '## Equipment Catalog',
    '',
    `The full catalog contains ${ITEMS.length} item definitions: 35 weapons (7 weapon types x 5 rarities), 60 armor pieces (3 armor sets x 4 slots x 5 rarities), and 60 accessories (12 designs x 5 rarities).`,
    '',
    '### Weapons',
    '',
    '| Item ID | Weapon Type | Rarity | Name | Base Stats | Drop Chapters |',
    '| --- | --- | --- | --- | --- | --- |',
  );

  const weapons = ITEMS.filter((i) => i.slot === 'weapon');
  for (const w of weapons) {
    const statsStr = formatStats(w.baseStats);
    const chStr = w.dropChapters.join(', ');
    push(`| \`${w.id}\` | \`${w.weaponType}\` | \`${w.rarity}\` | ${w.name} | ${statsStr} | Chapters ${chStr} |`);
  }

  push(
    '',
    '### Armor Sets',
    '',
    '| Item ID | Set | Slot | Rarity | Name | Base Stats | Drop Chapters |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  );

  const armors = ITEMS.filter((i) => i.slot !== 'weapon' && ['helmet', 'armor', 'gloves', 'boots'].includes(i.slot));
  for (const a of armors) {
    const statsStr = formatStats(a.baseStats);
    const chStr = a.dropChapters.join(', ');
    push(`| \`${a.id}\` | \`${a.visual.set}\` | \`${a.slot}\` | \`${a.rarity}\` | ${a.name} | ${statsStr} | Chapters ${chStr} |`);
  }

  push(
    '',
    '### Accessories',
    '',
    '| Item ID | Slot | Design | Rarity | Name | Base Stats | Drop Chapters |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  );

  const accessories = ITEMS.filter((i) => ['collar', 'earring', 'ring', 'charm'].includes(i.slot));
  for (const acc of accessories) {
    const statsStr = formatStats(acc.baseStats);
    const chStr = acc.dropChapters.join(', ');
    push(`| \`${acc.id}\` | \`${acc.slot}\` | \`${acc.visual.set}\` | \`${acc.rarity}\` | ${acc.name} | ${statsStr} | Chapters ${chStr} |`);
  }

  push('');
  return lines.join('\n');
}

describe('v2 content docs generator', () => {
  it('generates identical output on consecutive runs (deterministic)', () => {
    const run1 = generateContentDocs();
    const run2 = generateContentDocs();
    expect(run1).toBe(run2);
  });

  it('contains every single id in the content registry', () => {
    const doc = generateContentDocs();

    // Classes
    for (const c of CONTENT.classes) {
      expect(doc, `missing class id ${c.id}`).toContain(c.id);
      expect(doc, `missing starter weapon ${c.starterWeaponId}`).toContain(c.starterWeaponId);
    }

    // Weapon profiles
    for (const w of CONTENT.weaponTypes) {
      expect(doc, `missing weaponType id ${w.id}`).toContain(w.id);
    }

    // Slots
    for (const s of CONTENT.slots) {
      expect(doc, `missing slot id ${s.id}`).toContain(s.id);
    }

    // Rarities
    for (const r of CONTENT.rarities) {
      expect(doc, `missing rarity id ${r.id}`).toContain(r.id);
    }

    // Stats
    for (const st of CONTENT.stats) {
      expect(doc, `missing stat id ${st.id}`).toContain(st.id);
    }

    // Materials
    for (const m of CONTENT.materials) {
      expect(doc, `missing material id ${m.id}`).toContain(m.id);
    }

    // Monsters
    for (const mon of CONTENT.monsters) {
      expect(doc, `missing monster id ${mon.id}`).toContain(mon.id);
    }

    // Chapters
    for (const ch of CONTENT.chapters) {
      expect(doc, `missing chapter id ${ch.id}`).toContain(ch.id);
    }

    // Recipes & Salvage
    for (const rc of CONTENT.recipes) {
      expect(doc, `missing recipe id ${rc.id}`).toContain(rc.id);
    }
    expect(doc, `missing relic recipe id ${RELIC_RECIPE.id}`).toContain(RELIC_RECIPE.id);

    // Chests
    for (const chestId of Object.keys(CONTENT.chests)) {
      expect(doc, `missing chest table id ${chestId}`).toContain(chestId);
    }

    // Items
    for (const item of CONTENT.items) {
      expect(doc, `missing item id ${item.id}`).toContain(item.id);
    }
  });

  it('renders valid markdown tables without broken pipes', () => {
    const doc = generateContentDocs();
    const lines = doc.split('\n');
    let inTable = false;
    let expectedPipes = 0;

    for (let i = 0; i < lines.length; i++) {
      const line = lines[i]!.trim();
      if (line.startsWith('|') && line.endsWith('|')) {
        const pipeCount = (line.match(/\|/g) || []).length;
        if (!inTable) {
          inTable = true;
          expectedPipes = pipeCount;
        } else {
          expect(pipeCount, `line ${i + 1} has ${pipeCount} pipes, expected ${expectedPipes}: "${line}"`).toBe(expectedPipes);
        }
      } else {
        inTable = false;
      }
    }
  });

  it('writes docs/content-v2.md when UPDATE_DOCS=1 and matches disk contents otherwise', () => {
    const generated = generateContentDocs();
    if (process.env.UPDATE_DOCS === '1') {
      writeFileSync(DOC_PATH, generated, 'utf8');
    }
    expect(existsSync(DOC_PATH), `docs/content-v2.md does not exist at ${DOC_PATH}`).toBe(true);
    const disk = readFileSync(DOC_PATH, 'utf8');
    expect(disk).toBe(generated);
  });
});
