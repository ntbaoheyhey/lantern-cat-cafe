import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const root=process.env.PROOF_ROOT;
const require=createRequire(process.env.PLAYWRIGHT_PACKAGE || `${root}/apps/web/package.json`);
const {chromium}=require(process.env.PLAYWRIGHT_CORE || '@playwright/test');
const source=readFileSync(`${root}/apps/web/e2e/support/visual-fonts.ts`,'utf8');
const fonts=[...source.matchAll(/family: '([^']+)', weights: \[([^\]]+)\],[\s\S]*?url: '([^']+)',[\s\S]*?sha256: '([^']+)'/g)];
const browser=await chromium.launch({args:['--no-sandbox'],executablePath:process.env.CHROMIUM_EXECUTABLE||undefined});
const records=[];
const dir=process.env.PROOF_OUTPUT;
mkdirSync(dir,{recursive:true});
try{
 for(const width of [1280,1600]) {
  const page=await browser.newPage({viewport:{width,height:width===1280?720:900},reducedMotion:'reduce'});
  await page.clock.install({time:Date.UTC(2026,10,3,12)});
  await page.clock.pauseAt(Date.UTC(2026,10,3,12));
  await page.addInitScript(()=>localStorage.setItem('taskbar-hero.howToPlaySeen','1'));
  const css=[];
  for(const [,family,weights,url,hash] of fonts){
   const response=await page.request.get(url);assert.ok(response.ok());const body=await response.body();
   assert.equal(createHash('sha256').update(body).digest('hex'),hash);
   await page.route(url,r=>r.fulfill({contentType:'font/woff2',headers:{'access-control-allow-origin':'*'},body}));
   for(const weight of weights.split(','))css.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:${weight.trim()};font-display:swap;src:url('${url}') format('woff2');}`);
  }
  await page.route('https://fonts.googleapis.com/**',r=>r.fulfill({contentType:'text/css',body:css.join('\n')}));
  page.on('pageerror',e=>console.log('PAGE ERROR',e.message));
  const response=await page.goto(process.env.PROOF_URL+'/#landing');
  console.log('NAV',response.status(),await page.locator('body').innerText());
  for(const screen of ['landing','class']){
   if(screen==='class')await page.getByTestId('landing-start').click();
   await page.getByTestId(screen==='landing'?'landing-hero':'class-picker').waitFor();
   await page.evaluate(()=>document.fonts.ready);await page.clock.runFor(40);await page.evaluate(()=>document.fonts.ready);
   assert.equal(await page.locator('[data-art2]').count(),0);
   const path=`${dir}/${screen}-${width}.png`;
   const png=await page.screenshot({animations:'disabled',path});
   records.push({screen,width,sha256:createHash('sha256').update(png).digest('hex'),platform:process.platform,browser:browser.version(),geometry:await page.locator('.landing__proof-pill').evaluateAll(es=>es.map(e=>e.getBoundingClientRect().toJSON()))});
  }
  await page.close();
 }
}finally{await browser.close();}
writeFileSync(`${dir}/source.json`,JSON.stringify({source:'Native unedited Playwright screenshots, fixed clock and pinned existing fonts. Generated by gameplay-platform-capture.mjs.',records},null,2)+'\n');
console.log(records.map(({screen,width,sha256,platform,browser})=>({screen,width,sha256,platform,browser})));
