#!/usr/bin/env bash
# Verify a pull request in a retained worktree without spending GitHub Actions minutes.
# Usage: scripts/verify-pr.sh <pr-number> [--comment]   (FORCE_ALL=1 runs every step)
# The PR head is merged with the latest origin/main first, so the result is what main would be.
# Steps run only when the PR changed files they cover: docs-only PRs run just the drift check.
# --comment posts the result as a PR comment through the gh CLI.
set -uo pipefail
PR="${1:-}"; COMMENT="${2:-}"
if ! [[ "$PR" =~ ^[1-9][0-9]*$ ]]; then
  echo "Expected a positive PR number" >&2
  exit 2
fi
ROOT="$(git rev-parse --show-toplevel)"; DIR="${TMPDIR:-/tmp}/verify-pr-$PR"
LOG="$DIR.log"
# Never erase an earlier checkout, a log, or a symlink to somebody else's data.
if [ -e "$DIR" ] || [ -L "$DIR" ] || [ -e "$LOG" ] || [ -L "$LOG" ]; then
  echo "Refusing to overwrite existing verification data: $DIR or $LOG" >&2
  exit 2
fi
(set -o noclobber; : > "$LOG") || exit 2
cd "$ROOT"
printf 'VERIFIER_HEAD=%s\n' "$(git rev-parse HEAD)" >> "$LOG"
git fetch -q origin "+refs/heads/main:refs/remotes/origin/main" "+pull/$PR/head:refs/verify/pr-$PR" || exit 2
git worktree add -q --detach "$DIR" "refs/verify/pr-$PR" || exit 2
cd "$DIR"
printf 'PR_HEAD=%s\nBASE_HEAD=%s\n' "$(git rev-parse HEAD)" "$(git rev-parse origin/main)" >> "$LOG"
RESULTS=(); FAIL=0
run() { # name, command...
  local name="$1"; shift
  echo "== $name" >> "$LOG"
  # Keep token-shaped credentials out of logs; pipefail preserves the command result.
  if "$@" 2>&1 | sed -E 's/eyJ[A-Za-z0-9_-]{8,}[.]eyJ[A-Za-z0-9_-]{8,}[.][A-Za-z0-9_-]{8,}/[REDACTED_JWT]/g' >> "$LOG"; then RESULTS+=("PASS  $name"); else RESULTS+=("FAIL  $name"); FAIL=1; fi
}
skip() { RESULTS+=("skip  $1 ($2)"); }
if git merge --no-edit -q -m "verify: merge latest main for PR #$PR [skip ci]" origin/main >> "$LOG" 2>&1; then RESULTS+=("PASS  merge with latest main"); else RESULTS+=("FAIL  merge with latest main (conflict)"); git merge --abort 2>/dev/null; FAIL=1; fi
printf 'TESTED_HEAD=%s\n' "$(git rev-parse HEAD)" >> "$LOG"
FILES="$(git diff --name-only origin/main HEAD)"
has() { [ -n "${FORCE_ALL:-}" ] || echo "$FILES" | grep -Eq "$1"; }
CODE=$(echo "$FILES" | grep -Ev '^(docs/|screenshots/)|\.md$' | grep -c . || true)
if [ "$FAIL" = 0 ] && { [ "$CODE" -gt 0 ] || [ -n "${FORCE_ALL:-}" ]; }; then
  run "pnpm install" pnpm install --frozen-lockfile
  run "generated deno.json has no drift" bash -c 'pnpm gen:deno && git diff --exit-code -- supabase/functions'
  run "typecheck" pnpm typecheck
  run "lint" pnpm lint
  run "unit tests" pnpm test
  run "build" pnpm build
  if has '^(apps/web/|packages/|pnpm-lock.yaml|package.json)'; then
    run "playwright e2e" bash -c 'cd apps/web && pnpm test:e2e'
  else skip "playwright e2e" "no web changes"; fi
  if has '^(contracts/|packages/chain/|\.gitmodules)'; then
    if command -v forge >/dev/null; then
      run "pinned contract submodules" git submodule update --init --recursive -- contracts/lib/forge-std contracts/lib/openzeppelin-contracts
      run "prepare pinned Solidity compiler" bash -c 'cd contracts && forge build'
      run "forge test" bash -c 'cd contracts && forge --offline test'
      run "chain ABI has no drift" bash -c 'cd contracts && node ../packages/chain/scripts/gen-abi.mjs && git diff --exit-code -- ../packages/chain'
    else RESULTS+=("skip  forge test (forge not installed here: run it in a contracts-capable session)"); fi
  else skip "forge test" "no contract changes"; fi
else
  skip "everything else" "docs-only change or earlier failure"
fi
if [ -n "$(git status --porcelain --untracked-files=normal)" ]; then
  RESULTS+=("FAIL  verification worktree changed; retained for inspection")
  git status --short >> "$LOG"
  FAIL=1
else RESULTS+=("PASS  verification worktree remains clean"); fi
SUMMARY="Verified outside GitHub Actions (scripts/verify-pr.sh, PR head merged with origin/main $(git rev-parse --short origin/main)):
$(printf '%s\n' "${RESULTS[@]}")"
echo "$SUMMARY"; echo "log: $LOG"
if [ "$COMMENT" = "--comment" ]; then
  BODY="$(printf '%s\n\n```\n%s\n```\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' "Local verification result:" "$SUMMARY")"
  gh api -X POST "repos/ntbaoheyhey/taskbar-hero/issues/$PR/comments" -f body="$BODY" >/dev/null && echo "commented on #$PR"
fi
cd "$ROOT"
echo "worktree retained for inspection: $DIR"
exit $FAIL
